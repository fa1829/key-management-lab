"""Module 03b -- Walk one encryption key through its full lifecycle over KMIP.

States follow NIST SP 800-57 Part 1 / KMIP: Pre-Active -> Active -> Deactivated -> Destroyed,
with Compromised as the off-ramp. This is the same protocol CipherTrust Manager and other
enterprise KMS platforms speak to databases, storage arrays and backup software.

Run (server must be up):  source config/lab.env && .venv-kmip/bin/python python/kmip_lifecycle.py
"""
import os
import sys
import warnings

warnings.filterwarnings("ignore")
from kmip.core import enums  # noqa: E402
from kmip.pie.client import ProxyKmipClient  # noqa: E402
from kmip.pie.exceptions import KmipOperationFailure  # noqa: E402

PKI = os.environ["PKI_DIR"]
CP = {  # cryptographic parameters for server-side AES-CBC encryption
    "block_cipher_mode": enums.BlockCipherMode.CBC,
    "padding_method": enums.PaddingMethod.PKCS5,
    "cryptographic_algorithm": enums.CryptographicAlgorithm.AES,
}
IV = bytes(16)  # fixed IV for a repeatable demo only; never reuse IVs in real systems

client = ProxyKmipClient(
    hostname="127.0.0.1", port=5696,
    cert=f"{PKI}/certs/kmip-client.crt", key=f"{PKI}/keys/kmip-client.key",
    ca=f"{PKI}/chain.pem", config_file=os.devnull,
)
log = []


def state(uid):
    _, attrs = client.get_attributes(uid, ["State"])
    return attrs[0].attribute_value.value.name


def step(n, action, uid, note=""):
    s = state(uid) if uid else "-"
    log.append((n, action, uid, s, note))
    print(f"[{n}] {action:<36} key {uid:<4} state={s:<12} {note}")


try:
    client.open()
except Exception as exc:  # noqa: BLE001
    sys.exit(f"Cannot reach the KMIP server ({exc}). Start it: ./scripts/03_kmip_server.sh start")

try:
    usage = [enums.CryptographicUsageMask.ENCRYPT, enums.CryptographicUsageMask.DECRYPT]

    # 1. Generation: the server creates the key; the client only ever gets an identifier.
    v1 = client.create(enums.CryptographicAlgorithm.AES, 256, name="payments-dek-v1",
                       cryptographic_usage_mask=usage)
    step(1, "Create AES-256 payments-dek-v1", v1, "generated by the server, not yet usable")

    # 2. Activation: the key may now protect data.
    client.activate(v1)
    step(2, "Activate v1", v1)
    ct_old = client.encrypt(b"card=4111111111111111;exp=12/29", uid=v1,
                            cryptographic_parameters=CP, iv_counter_nonce=IV)[0]
    step(3, "Encrypt a record with v1 (server)", v1, f"{len(ct_old)}-byte ciphertext")

    # 3. Discovery: applications find keys by name, not by copying them around.
    found = client.locate(attributes=[client.attribute_factory.create_attribute(
        enums.AttributeType.NAME, "payments-dek-v1")])
    step(4, "Locate by name", v1, f"found ids {found}")

    # 4. Rotation: a new version becomes the active key. Old data is re-encrypted under it
    #    while v1 is still active, then v1 is deactivated (archived).
    v2 = client.create(enums.CryptographicAlgorithm.AES, 256, name="payments-dek-v2",
                       cryptographic_usage_mask=usage)
    client.activate(v2)
    step(5, "Rotate: create + activate v2", v2, "new writes use v2")
    pt = client.decrypt(ct_old, uid=v1, cryptographic_parameters=CP, iv_counter_nonce=IV)
    client.encrypt(pt, uid=v2, cryptographic_parameters=CP, iv_counter_nonce=IV)
    step(6, "Re-encrypt old record: v1 -> v2", v2, "data migrated before v1 is retired")
    client.revoke(enums.RevocationReasonCode.CESSATION_OF_OPERATION, v1,
                  revocation_message="superseded by payments-dek-v2")
    step(7, "Deactivate v1 (revoke: superseded)", v1, "archived")
    for n, op in ((8, "encrypt"), (9, "decrypt")):
        try:
            getattr(client, op)(ct_old, uid=v1, cryptographic_parameters=CP, iv_counter_nonce=IV)
            step(n, f"{op.title()} with deactivated v1", v1, "allowed")
        except KmipOperationFailure as exc:
            step(n, f"{op.title()} with deactivated v1", v1, f"refused ({exc.reason.name})")
    print("    note: NIST SP 800-57 permits decrypt-only use of a deactivated key; this server is")
    print("          stricter, which is why step 6 re-encrypts before deactivation.")

    # 5. Destruction: after the retention period, the key material is destroyed.
    client.destroy(v1)
    try:
        client.get(v1)
        note = "UNEXPECTED: key still retrievable"
    except KmipOperationFailure as exc:
        note = f"get() now fails ({exc.reason.name})"
    log.append((10, "Destroy v1", v1, "DESTROYED", note))
    print(f"[10] {'Destroy v1':<36} key {v1:<4} state={'DESTROYED':<12} {note}")

    # 6. Compromise: a suspected leak moves a key straight to Compromised.
    v3 = client.create(enums.CryptographicAlgorithm.AES, 256, name="batch-export-key",
                       cryptographic_usage_mask=usage)
    client.activate(v3)
    client.revoke(enums.RevocationReasonCode.KEY_COMPROMISE, v3,
                  revocation_message="key found in a log file", compromise_occurrence_date=0)
    step(11, "Revoke batch-export-key: compromise", v3, "must never protect data again")
finally:
    client.close()

print("\nLifecycle demonstrated: generation, activation, use, discovery, rotation, archival, "
      "destruction and compromise -- all through KMIP over mutual TLS.")
